/**
 * Seed all 40 guest casual notes into IndexedDB Dexie
 */
export async function seed40GuestSampleNotes(): Promise<number> {
  const now = Date.now();
  let inserted = 0;

  for (let i = 0; i < GUEST_40_SAMPLE_NOTES.length; i++) {
    const item = GUEST_40_SAMPLE_NOTES[i];
    const excerpt = extractExcerptFromMarkdown(item.content, 'Guest Note');
    const tags = extractTagsFromMarkdown(item.content);
    const { wordCount, charCount } = countWordsAndChars(item.content);
    const timeOffset = (GUEST_40_SAMPLE_NOTES.length - i) * 1000 * 60 * 12; // staggered 12 mins

    const note: Note = {
      id: generateId(),
      rawMarkdown: item.content,
      excerpt,
      tags,
      wordCount,
      charCount,
      version: 1,
      isPinned: false,
      isDeleted: false,
      createdAt: now - timeOffset,
      updatedAt: now - timeOffset,
      isDirty: true,
      isOfficial: false,
      author: 'guest',
    };

    await db.notes.put(note);
    inserted++;
  }

  try {
    if (typeof window !== 'undefined') {
      localStorage.setItem('tagmesh_has_seeded_guest_notes_v1', 'true');
    }
  } catch {
    // ignore
  }

  return inserted;
}
